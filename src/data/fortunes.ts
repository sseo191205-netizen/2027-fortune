// Helper to find a fortune by ID (supporting e.g. "027" or "27" or "F027")
export function getFortuneById(idQuery: string | null | undefined): Fortune | null {
  if (!idQuery) return null;
  const cleanId = idQuery.replace(/[^0-9]/g, '').padStart(3, '0');
  const found = FORTUNES.find((f) => f.id === cleanId);
  return found || null;
}

// Draw a random fortune
export function getRandomFortune(): Fortune {
  const randomIndex = Math.floor(Math.random() * FORTUNES.length);
  return FORTUNES[randomIndex];
}
